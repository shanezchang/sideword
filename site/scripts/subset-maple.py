"""Generate Sideword's CN WOFF2 faces from the official v7.9 upright TTFs.

uv run scripts/subset-maple.py --source-dir /path/to/extracted-CN-fonts
Builds use the committed outputs and never download or regenerate fonts.
"""

import argparse
import hashlib
import json
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "public/fonts"
SOURCES = {
    "Regular": "0fcc5139bfd5ab14ff989bb7dfd5236d0cafc10e60b9828569e6883613ab4085",
    "SemiBold": "96ed7ae26ee7c50b02b2d2b2bc0f1a0cbabe45ae5d6e6abf6678e2177c415677",
    "Bold": "ca79870485fb382e01f4e70edb08bccd3cf1dbdf74b82023fdf2f0c95db55725",
}


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source-dir", required=True, type=Path)
    args = parser.parse_args()
    latin = OUT / "maple-latin.woff2"
    assert digest(latin) == ("e7080ef37fa8b3a38f71446e53e546634c27ce2cfe97673478cafc029d6344ee")
    latin_font = TTFont(latin)
    assert latin_font["name"].getDebugName(5) == "Version 7.900"
    assert [(a.axisTag, a.minValue, a.maxValue) for a in latin_font["fvar"].axes] == [
        ("wght", 100, 800)
    ]
    latin_points = set(latin_font.getBestCmap())
    inputs = ["content.mjs", "build.mjs", "app.js", "styles.css"]
    requested = {
        ord(c)
        for name in inputs
        for c in (ROOT / name).read_text()
        if ord(c) > 127 and not c.isspace() and ord(c) not in latin_points
    }
    files = {}
    sources = {"maple-latin.woff2": digest(latin)}
    css = "/* Generated by scripts/subset-maple.py from Sideword source text. */\n"
    fallback = set()
    for weight, name in zip([400, 600, 700], SOURCES, strict=True):
        source = args.source_dir / f"MapleMono-CN-{name}.ttf"
        assert digest(source) == SOURCES[name], f"Unexpected source: {source.name}"
        sources[source.name] = digest(source)
        font = TTFont(source, recalcTimestamp=False)
        assert font["name"].getDebugName(5) == "Version 7.900"
        assert font["OS/2"].usWeightClass == weight
        available = set(font.getBestCmap())
        points = requested & available
        fallback |= requested - available
        options = subset.Options()
        options.name_IDs = ["*"]
        options.name_legacy = True
        options.name_languages = ["*"]
        sub = subset.Subsetter(options=options)
        sub.populate(unicodes=points)
        sub.subset(font)
        font.flavor = "woff2"
        filename = f"maple-cn-{weight}.woff2"
        output = OUT / filename
        font.save(output)
        assert set(TTFont(output).getBestCmap()) == points
        files[filename] = {"bytes": output.stat().st_size, "sha256": digest(output)}
        ranges = ",".join(f"U+{c:X}" for c in sorted(points))
        css += (
            f'@font-face {{font-family:"Maple Mono CN";font-style:normal;'
            f"font-weight:{weight};font-display:swap;"
            f'src:url("/fonts/{filename}") format("woff2");'
            f"unicode-range:{ranges};}}\n"
        )
    (OUT / "maple-cn.css").write_text(css)
    files[latin.name] = {"bytes": latin.stat().st_size, "sha256": digest(latin)}
    manifest = {
        "version": "7.900",
        "fonttools": "4.68.0",
        "latinSource": "https://github.com/subframe7536/maple-font/blob/v7.9/woff2/var/MapleMono%5Bwght%5D-VF.woff2",
        "cnSource": "https://github.com/subframe7536/maple-font/releases/download/v7.9/MapleMono-CN-unhinted.zip",
        "sourceSha256": sources,
        "vocabularyInputs": {name: digest(ROOT / name) for name in inputs},
        "cnCodepoints": sorted(requested - fallback),
        "systemFallbackCodepoints": sorted(fallback),
        "files": files,
    }
    (OUT / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    print(json.dumps({"cnGlyphs": len(requested - fallback), "files": files}))


if __name__ == "__main__":
    main()
